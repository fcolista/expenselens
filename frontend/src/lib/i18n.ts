const dictionaries = { it, en };

function format(template: string, params: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (_, key) => String(params[key] ?? ''));
}

export const t = derived(lang, ($lang) => (key: string, params?: Record<string, string | number>) =>
  format(dictionaries[$lang][key] ?? dictionaries.it[key] ?? key, params));

export function translateServerError(text: string): string {
  return get(lang) === 'en' ? serverErrorsEn[text] ?? text : text;
}

const sessionErrors = ['Accesso richiesto', 'Sessione scaduta'];
export function isSessionError(text: string): boolean {
  return sessionErrors.some((item) => item === text || serverErrorsEn[item] === text);
}
