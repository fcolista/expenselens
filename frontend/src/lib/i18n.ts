export type Lang = 'it' | 'en';
export const LANG_KEY = 'expenselens-lang';

export const lang = writable<Lang>('it');

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'it' || saved === 'en') return saved;
  } catch { /* storage unavailable */ }
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('it') ? 'it' : 'en';
}

export function setLang(value: Lang) {
  lang.set(value);
  try { localStorage.setItem(LANG_KEY, value); } catch { /* ignore */ }
  if (typeof document !== 'undefined') document.documentElement.lang = value;
}

